const escapeHtml = (s: string) => s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]!);

/** Публичная страница политики: на неё ссылаются магазины приложений и сайт. */
export function privacyHtml(): string {
  const policy = privacyPolicy();
  const sections = policy.sections
    .map((s) => `<h2>${escapeHtml(s.heading)}</h2>${s.body.split("\n").map((p) => `<p>${escapeHtml(p)}</p>`).join("")}`)
    .join("");
  return `<!doctype html><html lang="ru"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${escapeHtml(policy.title)}</title>
<style>body{font:16px/1.55 -apple-system,Segoe UI,Roboto,sans-serif;max-width:720px;margin:0 auto;padding:24px 16px;color:#2c1810}
h1{font-size:26px}h2{font-size:18px;margin-top:28px}p{margin:8px 0}.d{color:#888}</style></head>
<body><h1>${escapeHtml(policy.title)}</h1><p class="d">Редакция от ${escapeHtml(policy.updatedAt)}</p>${sections}</body></html>`;
}
